def translate_city(name):
    if name in CITY_TRANS:
        return CITY_TRANS[name]
    # Загальні правила заміни
    res = name
    res = res.replace('ё', 'е').replace('Ё', 'Е')
    res = res.replace('ск', 'ськ').replace('ий', 'ий').replace('ое', 'е')
    res = res.replace('Подольский', 'Подільський').replace('Волынский', 'Волинський')
    res = res.replace('Северский', 'Сіверський').replace('Днестровский', 'Дністровський')
    return res

